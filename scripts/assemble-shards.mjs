import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');
const DRAFTS_ROOT = path.join(ROOT, 'scripts', '.drafts');
const ARTICLES_DIR = path.join(ROOT, 'src', 'data', 'articles');

const SHARDS = [
  ['01', 'shard01', 'shard01_enterprise_pain_ops.ts'],
  ['02', 'shard02', 'shard02_enterprise_pain_growth.ts'],
  ['03', 'shard03', 'shard03_ai_data_pipeline_a.ts'],
  ['04', 'shard04', 'shard04_ai_data_rag_evals.ts'],
  ['05', 'shard05', 'shard05_ai_data_bi_ops.ts'],
  ['06', 'shard06', 'shard06_ai_security_owasp.ts'],
  ['07', 'shard07', 'shard07_ai_security_privacy.ts'],
  ['08', 'shard08', 'shard08_ai_security_ip_zerotrust.ts'],
  ['09', 'shard09', 'shard09_github_vibecode_agents.ts'],
  ['10', 'shard10', 'shard10_github_orchestration_mcp.ts'],
  ['11', 'shard11', 'shard11_github_scrape_rag_mem.ts'],
  ['12', 'shard12', 'shard12_github_inference_guardrails.ts'],
  ['13', 'shard13', 'shard13_github_evals_ops_stack.ts'],
  ['14', 'shard14', 'shard14_models_peer_tier.ts'],
  ['15', 'shard15', 'shard15_mcp_slash_skills.ts'],
];

const onlyShard = process.argv.find((a) => a.startsWith('--shard='))?.split('=')[1];

let assembledShards = 0;
let totalArticles = 0;

for (const [num, shardId, filename] of SHARDS) {
  if (onlyShard && shardId !== onlyShard) continue;
  const draftDir = path.join(DRAFTS_ROOT, shardId);
  if (!fs.existsSync(draftDir)) continue;

  const jsonFiles = fs
    .readdirSync(draftDir)
    .filter((f) => f.endsWith('.json'))
    .sort();

  if (jsonFiles.length === 0) continue;

  const articles = [];
  for (const jf of jsonFiles) {
    const fullPath = path.join(draftDir, jf);
    const raw = fs.readFileSync(fullPath, 'utf8');
    let parsed;
    try {
      parsed = JSON.parse(raw);
    } catch (err) {
      throw new Error(`Invalid JSON in ${fullPath}: ${err.message}`);
    }
    const items = Array.isArray(parsed) ? parsed : [parsed];
    for (const rawArt of items) {
      const art = { ...rawArt };
      delete art.shardFile;
      delete art.track;
      delete art.blockRecipe;
      delete art.repoFullName;

      articles.push({
        ...art,
        shardId,
        readingMinutes: Number(art.readingMinutes) || 11,
        publishedAt: art.publishedAt || '2026-11-19',
        updatedAt: art.updatedAt || '2026-11-21',
        coverAlt: art.coverAlt || art.title,
        screenshotCaption:
          art.screenshotCaption || `Biểu đồ thống kê & chỉ số phân tích chuyên sâu: ${art.title}`,
        painPoints: Array.isArray(art.painPoints) ? art.painPoints : [],
        implementationChallenges: Array.isArray(art.implementationChallenges)
          ? art.implementationChallenges
          : [],
        solutionSteps: Array.isArray(art.solutionSteps) ? art.solutionSteps : [],
        sections: Array.isArray(art.sections) ? art.sections : [],
      });
    }
  }

  articles.sort((a, b) => Number(a.number) - Number(b.number));

  const outPath = path.join(ARTICLES_DIR, filename);
  const tsContent = `import type { BoostArticle } from '../boostTypes.ts';

// Auto-generated by scripts/assemble-shards.mjs from scripts/.drafts/${shardId}
export const BOOST_SHARD_${num}: BoostArticle[] = ${JSON.stringify(articles, null, 2)};
`;

  fs.writeFileSync(outPath, tsContent, 'utf8');
  assembledShards += 1;
  totalArticles += articles.length;
  console.log(`Assembled ${shardId} -> src/data/articles/${filename} (${articles.length} articles)`);
}

console.log(`Done. Assembled ${assembledShards} shards (${totalArticles} total shard articles).`);
