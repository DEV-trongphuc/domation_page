import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { BOOST_ALL_ARTICLES } from '../src/data/boostArticlesAllServer.ts';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');
const OUT_PATH = path.join(ROOT, 'src', 'data', 'boostSeoTopicsExtra.ts');

const STAGE_BY_INTENT = {
  Informational: 'TOFU',
  Comparison: 'MOFU',
  Commercial: 'BOFU',
  Transactional: 'BOFU',
};

const topics = BOOST_ALL_ARTICLES.filter((art) => Number(art.number) >= 77).map((art) => ({
  id: Number(art.number),
  code: `SEO-${String(art.number).padStart(3, '0')}`,
  pillar: art.pillar,
  pillarLabel: art.pillarLabel,
  title: art.title,
  primaryKeyword: art.focusKeyword,
  secondaryKeywords: art.secondaryKeywords.slice(0, 3),
  searchIntent: art.searchIntent,
  funnelStage: STAGE_BY_INTENT[art.searchIntent] || 'MOFU',
  targetPainPoint: art.thumbnailHook || art.metaDescription.slice(0, 110),
  targetLandingPage: art.relatedModuleUrl || '/boost',
  geoAnswerAngle: art.tldrSummary.slice(0, 145),
  linkedArticleSlug: art.slug,
}));

const content = `import type { SeoTopicItem } from './boostTypes';

// Auto-generated by scripts/build-seo-topics-extra.mjs — DO NOT EDIT MANUALLY.
export const BOOST_EXTRA_EXPANSION_SEO_TOPICS: SeoTopicItem[] = ${JSON.stringify(topics, null, 2)};
`;

fs.writeFileSync(OUT_PATH, content, 'utf8');
console.log(`Generated ${OUT_PATH} (${topics.length} mapped expansion SEO topics).`);
